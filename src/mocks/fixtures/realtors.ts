/**
 * Additional SAMPLE team members. They appear on their firm's page and have
 * their own profiles, but are not part of the Find Realtor directory
 * (`REALTORS`), so the "by firm" view still shows one card per firm.
 */
type MemberInput = Pick<Realtor, "slug" | "name" | "role" | "gender" | "since" | "languages" | "localities" | "specializations" | "bio"> & {
  photo: number;
  subRegions?: string[];
  buildings?: string[];
  reraId: string;
};

function member(firmId: string, m: MemberInput): Realtor {
  const principal = REALTORS.find((r) => r.firmId === firmId)!;
  const { photo: photoIndex, ...rest } = m;
  return {
    ...principal,
    ...rest,
    id: `${firmId}-${m.slug}`,
    firmId,
    buildings: m.buildings ?? [],
    subRegions: m.subRegions ?? principal.subRegions,
    association: principal.association,
    credentials: principal.credentials.filter((c) => c !== "GST"),
    gstin: undefined,
    photo: photo(photoIndex),
    saleListings: 0,
    rentalListings: 0,
    rating: 4.6,
    deals: 0,
  };
}

